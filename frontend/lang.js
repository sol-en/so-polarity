window.currentLang = localStorage.getItem('zhbk_lang') || 'uk';

window.t = function(key) {
    if (!key) return key;
    const cleanKey = String(key).trim();
    if (dict[cleanKey] && dict[cleanKey][window.currentLang]) {
        return dict[cleanKey][window.currentLang];
    }
    for (const k in dict) {
        if (dict[k].uk === cleanKey || dict[k].en === cleanKey) {
            return dict[k][window.currentLang] || cleanKey;
        }
    }
    return key;
};

window.toggleLang = function() {
    window.currentLang = window.currentLang === 'uk' ? 'en' : 'uk';
    localStorage.setItem('zhbk_lang', window.currentLang);
    location.reload();
};

document.addEventListener('DOMContentLoaded', () => {
    // Add language toggle button to header
    const headerActions = document.querySelector('.header-actions');
    if (headerActions) {
        const langBtn = document.createElement('button');
        langBtn.className = 'btn btn-secondary';
        langBtn.style.marginRight = '10px';
        langBtn.innerHTML = window.currentLang === 'uk' ? '🇬🇧 EN' : '🇺🇦 UK';
        langBtn.title = "Перемкнути мову / Toggle language";
        langBtn.onclick = window.toggleLang;
        headerActions.prepend(langBtn);
    }
    // Auto translate text nodes in DOM that match dictionary keys
    function translateNode(node) {
        if (node.nodeType === 3) {
            let text = node.nodeValue.trim();
            if (text) {
                const trans = window.t(text);
                if (trans && trans !== text) {
                    node.nodeValue = node.nodeValue.replace(text, trans);
                } else if (window.currentLang === 'en') {
                    // Substring replacements for composite nodes in English mode
                    let updated = node.nodeValue;
                    if (updated.includes('кв. №')) updated = updated.replace(/кв\.\s*№/g, 'Apt. #');
                    if (updated.includes('вул. Михайла Грушевського, 14')) updated = updated.replace(/вул\.\s*Михайла Грушевського,\s*14/g, '14 Mykhailo Hrushevsky St.');
                    if (updated.includes('Площа:')) updated = updated.replace(/Площа:/g, 'Area:');
                    if (updated.includes('станом на')) updated = updated.replace(/станом на/g, 'as of');
                    if (updated.includes('квартплата + ліфт + газ')) updated = updated.replace(/квартплата \+ ліфт \+ газ/g, 'maintenance + elevator + gas');
                    if (updated !== node.nodeValue) {
                        node.nodeValue = updated;
                    }
                }
            }
        } else if (node.nodeType === 1 && node.nodeName !== 'SCRIPT' && node.nodeName !== 'STYLE') {
            if (node.placeholder) {
                const trans = window.t(node.placeholder);
                if (trans && trans !== node.placeholder) {
                    node.placeholder = trans;
                }
            }
            if (node.title) {
                const trans = window.t(node.title);
                if (trans && trans !== node.title) {
                    node.title = trans;
                }
            }
            node.childNodes.forEach(translateNode);
        }
    }
    
    translateNode(document.body);
    
    const observer = new MutationObserver(mutations => {
        mutations.forEach(mutation => {
            mutation.addedNodes.forEach(addedNode => {
                translateNode(addedNode);
            });
            if (mutation.type === 'characterData') {
                let text = mutation.target.nodeValue.trim();
                if (text) {
                    const trans = window.t(text);
                    if (trans && trans !== text) {
                        mutation.target.nodeValue = mutation.target.nodeValue.replace(text, trans);
                    }
                }
            }
        });
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
});
